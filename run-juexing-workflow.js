#!/usr/bin/env node
/**
 * 決行公文歸檔工作流啟動器（人機合作版）
 *
 * 使用流程：
 * 1. 執行：node run-juexing-workflow.js
 * 2. 手動登入 GDMS，點開任一決行公文
 * 3. 系統自動偵測並讀取公文資訊，推送到 Telegram
 * 4. 回覆 1 = 自動歸檔，2 = 自己處理
 */

require('dotenv').config();
const workflow = require('./src/workflow-juexing');

console.log(`
╔════════════════════════════════════════════════════════════════╗
║             ⚖️  決行公文歸檔系統啟動                            ║
╠════════════════════════════════════════════════════════════════╣
║                                                                ║
║  使用流程：                                                    ║
║  1️⃣  系統開啟 GDMS 登入頁面                                   ║
║  2️⃣  你手動登入，點開任一決行公文                             ║
║  3️⃣  系統自動偵測並讀取：                                     ║
║      • 公文本身（主旨、受文者、日期）                          ║
║      • 擬辦意見                                               ║
║      • 校長意見（悉/可...）                                   ║
║  4️⃣  Telegram 推送，等你回覆                                  ║
║                                                                ║
║  Telegram 指令：                                              ║
║  • 回覆「1」= ✅ 自動歸檔（點傳送歸檔）                       ║
║  • 回覆「2」= 🙋 我來處理（繼續下一份）                      ║
║                                                                ║
║  （系統持續待機，不會自動關閉）                                ║
╚════════════════════════════════════════════════════════════════╝
`);

workflow.run()
  .then(() => {
    console.log('\n✅ 所有決行公文處理完成！');
    process.exit(0);
  })
  .catch(err => {
    console.error('\n❌ 工作流出錯：', err.message);
    process.exit(1);
  });
