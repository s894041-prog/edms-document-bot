#!/usr/bin/env node
/**
 * 便簽自動化工作流啟動器
 *
 * 使用流程：
 * 1. 執行此指令：node run-bianqian-workflow.js
 * 2. 等待系統提示，然後手動開啟便簽編輯器（DocEditorHome）
 * 3. 系統自動生成便簽建議稿
 * 4. 在 Telegram 回覆 1/2/3 進行確認
 * 5. 完成後自動填入並保存
 */

require('dotenv').config();
const workflow = require('./src/workflow-bianqian');

console.log(`
╔════════════════════════════════════════════════════════════════╗
║               🤖 便簽自動化工作流啟動                          ║
╠════════════════════════════════════════════════════════════════╣
║                                                                ║
║  ⏳ 等待你手動開啟便簽編輯器 (DocEditorHome)...               ║
║                                                                ║
║  一旦開啟，系統將自動：                                        ║
║  1️⃣  生成便簽建議稿                                           ║
║  2️⃣  發送到 Telegram 徵詢                                     ║
║  3️⃣  根據你的回覆自動填入或修改                              ║
║  4️⃣  自動保存                                                ║
║                                                                ║
║  Telegram 指令：                                              ║
║  • 回覆「1」= ✅ 同意並自動送出                               ║
║  • 回覆「2」= ✏️ 要求修改（說明修改意見）                    ║
║  • 回覆「3」= 🙋 自己處理                                     ║
║                                                                ║
╚════════════════════════════════════════════════════════════════╝
`);

workflow.run()
  .then(() => {
    console.log('\n✅ 工作流成功完成！');
    process.exit(0);
  })
  .catch(err => {
    console.error('\n❌ 工作流出錯：', err.message);
    process.exit(1);
  });
